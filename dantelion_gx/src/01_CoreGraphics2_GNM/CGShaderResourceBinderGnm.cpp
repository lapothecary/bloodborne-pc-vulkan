inline bool BindShaderHeaderToStageImpl(
    CGShaderResourceBinderGnm* self,
    uint32_t stage_idx,
    const CGShaderBindingHeaderGnm* shader_hdr)
{
    CGStageDependencyCacheGnm& st = self->stages[stage_idx];
    if (st.bound_shader_hdr == shader_hdr) {
        return false;
    }
    if (shader_hdr) {
        const uint64_t* dep_table = shader_hdr->dep_bitmask_table;
        uint64_t mask_lo = shader_hdr->active_srv_mask_lo;
        st.active_srv_mask_lo = mask_lo;
        while (mask_lo) {
            uint32_t bit = __builtin_ctzll(mask_lo);
            st.srv_lo_dep_masks[bit] = dep_table[shader_hdr->srv_lo_dep_idx[bit]];
            mask_lo &= (mask_lo - 1);
        }
        uint64_t mask_hi = shader_hdr->active_srv_mask_hi;
        st.active_srv_mask_hi = mask_hi;
        while (mask_hi) {
            uint32_t bit = __builtin_ctzll(mask_hi);
            st.srv_hi_dep_masks[bit] = dep_table[shader_hdr->srv_hi_dep_idx[bit]];
            mask_hi &= (mask_hi - 1);
        }
        uint64_t mask_other = shader_hdr->active_other_mask;
        st.active_other_mask = mask_other;
        while (mask_other) {
            uint32_t bit = __builtin_ctzll(mask_other);
            st.other_dep_masks[bit] = dep_table[shader_hdr->other_dep_idx[bit]];
            mask_other &= (mask_other - 1);
        }
        st.dirty_cmd_mask    = ~0ULL;
        st.fetch_cmd_bitmask = (shader_hdr->fetch_shader_cmd_idx < 64)
            ? (1ULL << shader_hdr->fetch_shader_cmd_idx) : 0ULL;
        st.srt_cmd_bitmask   = (shader_hdr->srt_root_cmd_idx < 64)
            ? (1ULL << shader_hdr->srt_root_cmd_idx) : 0ULL;
    } else {
        st.active_srv_mask_lo = 0;
        st.active_srv_mask_hi = 0;
        st.active_other_mask  = 0;
        st.dirty_cmd_mask     = 0;
    }
    st.bound_shader_hdr = shader_hdr;
    return true;
}

inline void ExecuteStageBindingBytecode(
    CGShaderResourceBinderGnm* self,
    uint8_t* gnmx_ctx,
    void* staging_pool,
    const CGShaderBindingHeaderGnm* hdr,
    uint32_t binder_stage_idx,
    uint32_t gnm_stage,
    uint32_t gds_range_dword)
{
    CGStageDependencyCacheGnm& st = self->stages[binder_stage_idx];
    uint64_t dirty_cmds = st.dirty_cmd_mask;
    const uint32_t num_cmds = hdr->num_binding_cmds;
    if (num_cmds <= 63u) {
        dirty_cmds &= (1ULL << num_cmds) - 1ULL;
    }
    if (dirty_cmds == 0ULL) {
        return;
    }

    const uint32_t* cmds = hdr->binding_cmds;
    uint32_t* srt_dwords = self->srt_user_data_dwords[gnm_stage];

    const bool direct_ud = gx_direct_vk::EnabledV2Sub(gx_direct_vk::kV2Sub_StageUserData);
    gx_direct_vk::StageUserDataBatch ud_batch{};

    auto fn_setVsharp = reinterpret_cast<void(*)(void*, uint32_t, uint32_t, const void*)>(GX_VMA(0x10761a0ULL));
    auto fn_setTsharp = reinterpret_cast<void(*)(void*, uint32_t, uint32_t, const void*)>(GX_VMA(0x1076240ULL));
    auto fn_setSsharp = reinterpret_cast<void(*)(void*, uint32_t, uint32_t, const void*)>(GX_VMA(0x10762f0ULL));
    auto fn_setPtr    = reinterpret_cast<void(*)(void*, uint32_t, uint32_t, void*)>(GX_VMA(0x1076390ULL));
    auto fn_setUserD  = reinterpret_cast<void(*)(void*, uint32_t, uint32_t, uint32_t)>(GX_VMA(0x1076420ULL));
    auto fn_suballoc  = reinterpret_cast<void*(*)(void*, void*, uint64_t)>(GX_VMA(0x26addc0ULL));

    auto emit_vsharp = [&](uint32_t dst_reg, const void* sharp) noexcept {
        if (direct_ud) {
            ud_batch.SetDwords(gnmx_ctx, gnm_stage, dst_reg, sharp, 4u);
        } else {
            fn_setVsharp(gnmx_ctx, gnm_stage, dst_reg, sharp);
        }
    };
    auto emit_tsharp = [&](uint32_t dst_reg, const void* sharp) noexcept {
        if (direct_ud) {
            ud_batch.SetDwords(gnmx_ctx, gnm_stage, dst_reg, sharp, 8u);
        } else {
            fn_setTsharp(gnmx_ctx, gnm_stage, dst_reg, sharp);
        }
    };
    auto emit_ssharp = [&](uint32_t dst_reg, const void* sharp) noexcept {
        if (direct_ud) {
            ud_batch.SetDwords(gnmx_ctx, gnm_stage, dst_reg, sharp, 4u);
        } else {
            fn_setSsharp(gnmx_ctx, gnm_stage, dst_reg, sharp);
        }
    };
    auto emit_ptr = [&](uint32_t dst_reg, void* ptr) noexcept {
        if (direct_ud) {
            ud_batch.SetPtr(gnmx_ctx, gnm_stage, dst_reg, ptr);
        } else {
            fn_setPtr(gnmx_ctx, gnm_stage, dst_reg, ptr);
        }
    };
    auto emit_user_d = [&](uint32_t dst_reg, uint32_t val) noexcept {
        if (direct_ud) {
            ud_batch.SetDword(gnmx_ctx, gnm_stage, dst_reg, val);
        } else {
            fn_setUserD(gnmx_ctx, gnm_stage, dst_reg, val);
        }
    };

    while (dirty_cmds != 0ULL) {
        const uint32_t cmd_idx = static_cast<uint32_t>(__builtin_ctzll(dirty_cmds));
        dirty_cmds -= (1ULL << cmd_idx);

        const uint32_t cmd      = cmds[cmd_idx];
        const uint8_t  opcode   = static_cast<uint8_t>(cmd & 0xFFu);
        const uint8_t  dst_reg  = static_cast<uint8_t>((cmd >> 8) & 0xFFu);
        const uint8_t  src_slot = static_cast<uint8_t>((cmd >> 16) & 0xFFu);

        switch (opcode) {
        case 0:
            emit_vsharp(dst_reg, self->staged_srv_tsharps[binder_stage_idx][src_slot]);
            break;
        case 1:
            emit_tsharp(dst_reg, self->staged_srv_tsharps[binder_stage_idx][src_slot]);
            break;
        case 2:
            emit_vsharp(dst_reg, self->staged_uav_tsharps[binder_stage_idx][src_slot]);
            break;
        case 3:
            emit_tsharp(dst_reg, self->staged_uav_tsharps[binder_stage_idx][src_slot]);
            break;
        case 4:
            emit_ssharp(dst_reg, self->staged_sampler_ssharps[binder_stage_idx][src_slot]);
            break;
        case 5:
            emit_vsharp(dst_reg, self->staged_cb_vsharps[binder_stage_idx][src_slot]);
            break;
        case 6:
            emit_user_d(dst_reg, gds_range_dword);
            break;
        case 7:
        case 20: {
            void* tbl_gpu = self->allocated_global_table_gpu;
            if (tbl_gpu == nullptr) {
                void* ctx_ptr = gnmx_ctx;
                tbl_gpu = fn_suballoc(staging_pool, &ctx_ptr, 0xC0ULL);
                self->allocated_global_table_gpu = tbl_gpu;
                if (tbl_gpu != nullptr) {
                    std::memcpy(tbl_gpu, self->global_resource_table, 0xC0u);
                }
            }
            if (opcode == 7) {
                emit_ptr(dst_reg, tbl_gpu);
            } else if (dst_reg >= 16u) {
                const uint64_t addr = reinterpret_cast<uint64_t>(tbl_gpu);
                const int32_t idx   = static_cast<int32_t>(dst_reg) - 16;
                srt_dwords[idx]     = static_cast<uint32_t>(addr);
                srt_dwords[idx + 1] = static_cast<uint32_t>(addr >> 32);
            }
            break;
        }
        case 8:
        case 21: {
            uint32_t min_slot = 0x80u;
            uint32_t max_slot = 0x80u;
            if (st.active_srv_mask_lo != 0ULL) {
                min_slot = static_cast<uint32_t>(__builtin_ctzll(st.active_srv_mask_lo));
                max_slot = 63u - static_cast<uint32_t>(__builtin_clzll(st.active_srv_mask_lo));
            }
            if (st.active_srv_mask_hi != 0ULL) {
                if (min_slot == 0x80u) {
                    min_slot = 64u + static_cast<uint32_t>(__builtin_ctzll(st.active_srv_mask_hi));
                }
                max_slot = static_cast<uint32_t>(__builtin_clzll(st.active_srv_mask_hi)) ^ 0x7Fu;
            }
            if (min_slot == 0x80u) {
                break;
            }
            const uint64_t start_off  = static_cast<uint64_t>(min_slot) << 5;
            const uint64_t copy_bytes = static_cast<uint64_t>(max_slot + 1u - min_slot) << 5;
            void* ctx_ptr = gnmx_ctx;
            uint8_t* gpu_tbl = static_cast<uint8_t*>(fn_suballoc(staging_pool, &ctx_ptr, start_off + copy_bytes));
            if (gpu_tbl != nullptr) {
                std::memcpy(
                    gpu_tbl + start_off,
                    reinterpret_cast<const uint8_t*>(self->staged_srv_tsharps[binder_stage_idx]) + start_off,
                    copy_bytes);
            }
            if (opcode == 8) {
                emit_ptr(dst_reg, gpu_tbl);
            } else if (dst_reg >= 16u) {
                const uint64_t addr = reinterpret_cast<uint64_t>(gpu_tbl);
                const int32_t idx   = static_cast<int32_t>(dst_reg) - 16;
                srt_dwords[idx]     = static_cast<uint32_t>(addr);
                srt_dwords[idx + 1] = static_cast<uint32_t>(addr >> 32);
            }
            break;
        }
        case 9:
        case 22: {
            const uint64_t uav_bits = (st.active_other_mask & 0xFF000000000ULL) >> 36;
            if (uav_bits == 0ULL) {
                break;
            }
            const uint32_t min_slot    = static_cast<uint32_t>(__builtin_ctzll(uav_bits));
            const uint32_t count_slots = 64u - min_slot - static_cast<uint32_t>(__builtin_clzll(uav_bits));
            const uint64_t start_off   = static_cast<uint64_t>(min_slot) << 5;
            const uint64_t copy_bytes  = static_cast<uint64_t>(count_slots & 0x1FFFFFFFu) << 5;
            void* ctx_ptr = gnmx_ctx;
            uint8_t* gpu_tbl = static_cast<uint8_t*>(fn_suballoc(staging_pool, &ctx_ptr, start_off + copy_bytes));
            if (gpu_tbl != nullptr) {
                std::memcpy(
                    gpu_tbl + start_off,
                    reinterpret_cast<const uint8_t*>(self->staged_uav_tsharps[binder_stage_idx]) + start_off,
                    copy_bytes);
            }
            if (opcode == 9) {
                emit_ptr(dst_reg, gpu_tbl);
            } else if (dst_reg >= 16u) {
                const uint64_t addr = reinterpret_cast<uint64_t>(gpu_tbl);
                const int32_t idx   = static_cast<int32_t>(dst_reg) - 16;
                srt_dwords[idx]     = static_cast<uint32_t>(addr);
                srt_dwords[idx + 1] = static_cast<uint32_t>(addr >> 32);
            }
            break;
        }
        case 10:
        case 23: {
            const uint64_t samp_bits = st.active_other_mask & 0xFFFFULL;
            if (samp_bits == 0ULL) {
                break;
            }
            const uint32_t min_slot    = static_cast<uint32_t>(__builtin_ctzll(samp_bits));
            const uint32_t count_slots = 64u - min_slot - static_cast<uint32_t>(__builtin_clzll(samp_bits));
            const uint64_t start_off   = static_cast<uint64_t>(min_slot) << 4;
            const uint64_t copy_bytes  = static_cast<uint64_t>(count_slots & 0x3FFFFFFFu) << 4;
            void* ctx_ptr = gnmx_ctx;
            uint8_t* gpu_tbl = static_cast<uint8_t*>(fn_suballoc(staging_pool, &ctx_ptr, start_off + copy_bytes));
            if (gpu_tbl != nullptr) {
                std::memcpy(
                    gpu_tbl + start_off,
                    reinterpret_cast<const uint8_t*>(self->staged_sampler_ssharps[binder_stage_idx]) + start_off,
                    copy_bytes);
            }
            if (opcode == 10) {
                emit_ptr(dst_reg, gpu_tbl);
            } else if (dst_reg >= 16u) {
                const uint64_t addr = reinterpret_cast<uint64_t>(gpu_tbl);
                const int32_t idx   = static_cast<int32_t>(dst_reg) - 16;
                srt_dwords[idx]     = static_cast<uint32_t>(addr);
                srt_dwords[idx + 1] = static_cast<uint32_t>(addr >> 32);
            }
            break;
        }
        case 11:
        case 24: {
            const uint64_t cb_bits = (st.active_other_mask & 0xFFFFF0000ULL) >> 16;
            if (cb_bits == 0ULL) {
                break;
            }
            const uint32_t min_slot    = static_cast<uint32_t>(__builtin_ctzll(cb_bits));
            const uint32_t count_slots = 64u - min_slot - static_cast<uint32_t>(__builtin_clzll(cb_bits));
            const uint64_t start_off   = static_cast<uint64_t>(min_slot) << 4;
            const uint64_t copy_bytes  = static_cast<uint64_t>(count_slots & 0x3FFFFFFFu) << 4;
            void* ctx_ptr = gnmx_ctx;
            uint8_t* gpu_tbl = static_cast<uint8_t*>(fn_suballoc(staging_pool, &ctx_ptr, start_off + copy_bytes));
            if (gpu_tbl != nullptr) {
                std::memcpy(
                    gpu_tbl + start_off,
                    reinterpret_cast<const uint8_t*>(self->staged_cb_vsharps[binder_stage_idx]) + start_off,
                    copy_bytes);
            }
            if (opcode == 11) {
                emit_ptr(dst_reg, gpu_tbl);
            } else if (dst_reg >= 16u) {
                const uint64_t addr = reinterpret_cast<uint64_t>(gpu_tbl);
                const int32_t idx   = static_cast<int32_t>(dst_reg) - 16;
                srt_dwords[idx]     = static_cast<uint32_t>(addr);
                srt_dwords[idx + 1] = static_cast<uint32_t>(addr >> 32);
            }
            break;
        }
        case 13:
            if (dst_reg >= 16u) std::memcpy(&srt_dwords[static_cast<int32_t>(dst_reg) - 16], self->staged_srv_tsharps[binder_stage_idx][src_slot], 16);
            break;
        case 14:
            if (dst_reg >= 16u) std::memcpy(&srt_dwords[static_cast<int32_t>(dst_reg) - 16], self->staged_srv_tsharps[binder_stage_idx][src_slot], 32);
            break;
        case 15:
            if (dst_reg >= 16u) std::memcpy(&srt_dwords[static_cast<int32_t>(dst_reg) - 16], self->staged_uav_tsharps[binder_stage_idx][src_slot], 16);
            break;
        case 16:
            if (dst_reg >= 16u) std::memcpy(&srt_dwords[static_cast<int32_t>(dst_reg) - 16], self->staged_uav_tsharps[binder_stage_idx][src_slot], 32);
            break;
        case 17:
            if (dst_reg >= 16u) std::memcpy(&srt_dwords[static_cast<int32_t>(dst_reg) - 16], self->staged_sampler_ssharps[binder_stage_idx][src_slot], 16);
            break;
        case 18:
            if (dst_reg >= 16u) std::memcpy(&srt_dwords[static_cast<int32_t>(dst_reg) - 16], self->staged_cb_vsharps[binder_stage_idx][src_slot], 16);
            break;
        case 19:
            if (dst_reg >= 16u) srt_dwords[static_cast<int32_t>(dst_reg) - 16] = gds_range_dword;
            break;
        case 26: {
            const uint64_t copy_bytes = static_cast<uint64_t>(cmd >> 24) << 2;
            void* ctx_ptr = gnmx_ctx;
            void* gpu_eud = fn_suballoc(staging_pool, &ctx_ptr, copy_bytes);
            if (gpu_eud != nullptr) {
                std::memcpy(gpu_eud, &srt_dwords[src_slot], copy_bytes);
            }
            emit_ptr(dst_reg, gpu_eud);
            break;
        }
        default:
            break;
        }
    }

    if (direct_ud) {
        ud_batch.Flush(gnmx_ctx, gnm_stage);
    }

    st.dirty_srv_mask_lo &= ~st.active_srv_mask_lo;
    st.dirty_srv_mask_hi &= ~st.active_srv_mask_hi;
    st.dirty_other_mask  &= ~st.active_other_mask;
    st.dirty_cmd_mask     = 0ULL;
}
