// Shader metadata header generated by the offline Orbis shader compiler wrapper:
// Describes active SRV/CB/Sampler/UAV slot masks and the 27-opcode SGPR/EUD
// binding bytecode stream (`binding_cmds[0..num_binding_cmds-1]`).
struct CGShaderBindingHeaderGnm {
    uint64_t        active_srv_mask_lo;      // +0x000 (SRV slots 0..63)
    uint64_t        active_srv_mask_hi;      // +0x008 (SRV slots 64..127)
    uint64_t        active_other_mask;       // +0x010 (Samplers 0..15, CBs 16..35, UAVs 36..43, GDS 56)
    uint8_t         srv_lo_dep_idx[64];      // +0x018..+0x057
    uint8_t         srv_hi_dep_idx[64];      // +0x058..+0x097
    uint8_t         other_dep_idx[58];       // +0x098..+0x0d1
    uint8_t         uses_global_table;       // +0x0d2
    uint8_t         fetch_shader_cmd_idx;    // +0x0d3
    uint8_t         srt_root_cmd_idx;        // +0x0d4
    uint8_t         pad0d5[3];               // +0x0d5
    const uint64_t* dep_bitmask_table;       // +0x0d8
    const uint32_t* binding_cmds;            // +0x0e0 (array of 32-bit packed opcodes)
    uint32_t        num_binding_cmds;        // +0x0e8
    uint32_t        pad0ec;                  // +0x0ec
    uint64_t        global_cb_desc_lo;       // +0x0f0
    uint64_t        global_cb_desc_hi;       // +0x0f8
    uint8_t*        gnm_shader_object;       // +0x100 (sce::Gnmx::VsShader / PsShader / CsShader)
    void*           gnm_shader_binary_gpu;   // +0x108
};

// Per-stage resource dependency tracker (size 0x640 = 1600 bytes per stage, 6 stages)
struct CGStageDependencyCacheGnm {
    uint64_t                        dirty_srv_mask_lo;   // +0x000 (+0x18 in binder)
    uint64_t                        dirty_srv_mask_hi;   // +0x008 (+0x20 in binder)
    uint64_t                        dirty_other_mask;    // +0x010 (+0x28 in binder)
    uint64_t                        dirty_cmd_mask;      // +0x018 (+0x30 in binder)
    const CGShaderBindingHeaderGnm* bound_shader_hdr;    // +0x020 (+0x38 in binder)
    uint32_t                        uav_counter_base[8]; // +0x028..+0x047 (+0x40 in binder)
    uint64_t                        active_srv_mask_lo;  // +0x048 (+0x60 in binder)
    uint64_t                        active_srv_mask_hi;  // +0x050 (+0x68 in binder)
    uint64_t                        active_other_mask;   // +0x058 (+0x70 in binder)
    uint64_t                        srv_lo_dep_masks[64];// +0x060..+0x25f (+0x78 in binder)
    uint64_t                        srv_hi_dep_masks[64];// +0x260..+0x45f (+0x278 in binder)
    uint64_t                        other_dep_masks[58]; // +0x460..+0x62f (+0x478 in binder)
    uint64_t                        fetch_cmd_bitmask;   // +0x630 (+0x648 in binder)
    uint64_t                        srt_cmd_bitmask;     // +0x638 (+0x650 in binder)
};
static_assert(sizeof(CGStageDependencyCacheGnm) == 0x640, "Exact 0x640 per-stage dependency cache");

